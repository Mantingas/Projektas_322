/**
 * Regenerates the two files the public demo needs:
 *  - src/generated/demoSamples.ts  the synthetic sample CSVs as text, bundled into a lazily loaded chunk (the app never calls fetch/XHR, see tests/privacy.test.ts)
 *  - src/generated/demoFinding.json  the example finding on the landing page, produced by the real engine from those files
 */
import fs from 'node:fs';
import { buildDemoFinding } from './demoFindingBuild';
import { DEMO_FILES } from '../src/lib/demo';

const text: Record<string, string> = {};
for (const d of DEMO_FILES) text[d.file] = fs.readFileSync(`public/samples/${d.file}`, 'utf8');
fs.mkdirSync('src/generated', { recursive: true });
fs.writeFileSync('src/generated/demoSamples.ts', `// GENERATED by scripts/demo-finding.ts from public/samples (synthetic files). Do not edit.\nexport const DEMO_TEXT: Record<string, string> = ${JSON.stringify(text, null, 1)};\n`);
console.log('written src/generated/demoSamples.ts');

buildDemoFinding().then((d) => {
  fs.mkdirSync('src/generated', { recursive: true });
  fs.writeFileSync('src/generated/demoFinding.json', JSON.stringify(d, null, 2) + '\n');
  console.log('written src/generated/demoFinding.json');
}).catch((e) => { console.error(e); process.exit(1); });
